"""Import transparent 2x2 riverside kit sheets into independent map pieces."""
import json
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).parent / 'source/riverside'
OUT = ROOT / 'public/assets/river-kit'
SHEETS = {
 'shops-a': [('pavilion',440,300),('potion',480,340),('weapon',480,340),('smithy',480,340)],
 'shops-b': [('classhall',440,340),('gemshop',440,320),('travelarch',200,220),('minegate',468,300)],
 'river-props': [('tree',420,440),('boat',320,130),('dock',280,120),('stilt-house',340,260)],
}

def main():
 OUT.mkdir(parents=True,exist_ok=True)
 pieces = {}
 for sheet_name, specs in SHEETS.items():
  sheet=Image.open(SOURCE/f'{sheet_name}.png').convert('RGBA')
  if sheet.getchannel('A').getextrema()[0]>32: raise ValueError(f'{sheet_name}: transparency missing')
  sheet.putalpha(sheet.getchannel('A').point(lambda a:0 if a<96 else a))
  for index,(name,max_w,max_h) in enumerate(specs):
   c,r=index%2,index//2
   frame=sheet.crop((round(c*sheet.width/2),round(r*sheet.height/2),round((c+1)*sheet.width/2),round((r+1)*sheet.height/2)))
   box=frame.getbbox()
   if not box:raise ValueError(f'{name}: empty asset')
   frame=frame.crop(box)
   scale=min(max_w/frame.width,max_h/frame.height)
   size=(round(frame.width*scale),round(frame.height*scale))
   frame=frame.resize(size,Image.Resampling.LANCZOS)
   frame.save(OUT/f'{name}.webp','WEBP',quality=94,method=6)
   pieces[name]={'w':size[0],'h':size[1]}
   if name=='dock':
    alpha=frame.getchannel('A')
    surface=next(y for y in range(frame.height) if sum(alpha.getpixel((x,y))>128 for x in range(frame.width))>frame.width*.85)
    pieces[name]['surfaceRatio']=round(surface/frame.height,5)
   print(name,size)
 Image.open(SOURCE/'riverside-far.png').convert('RGB').save(OUT/'far-river.webp','WEBP',quality=92,method=6)
 if (SOURCE/'riverside-far-nangnon-v2.png').exists():
  Image.open(SOURCE/'riverside-far-nangnon-v2.png').convert('RGB').save(OUT/'far-nangnon-v2.webp','WEBP',quality=93,method=6)
 (OUT/'kit.json').write_text(json.dumps(pieces,indent=2)+'\n')
 (ROOT/'shared/riverside-pieces.js').write_text('// Generated by tools/town-kit/import_riverside.py.\nexport const RIVER_PIECES = '+json.dumps(pieces,indent=2)+';\n')

if __name__=='__main__':main()
